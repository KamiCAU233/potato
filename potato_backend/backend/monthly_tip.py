def get_monthly_tip(month: int = None) -> str:
    """返回当前月份对应的易发病提示。不传 month 则用系统当前月份。"""
    if month is None:
        month = datetime.datetime.now().month
    return _MONTH_TIPS.get(month, "请结合当地气候与田间表现做好病害防控。")
